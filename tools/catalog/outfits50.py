"""Extend the outfits to 50 rarities x 6 titles and regenerate src/shared/Avatars.luau.
    python3 tools/catalog/outfits50.py
Rarities 1-25 keep their checked outfits (2 extra mixes each); 26-50 come from fresh public catalog searches
(cached in catalog3.json)."""
import json, os, re, time, urllib.request, urllib.parse

S = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(S))
AV = os.path.join(ROOT, "src/shared/Avatars.luau")
CACHE = os.path.join(S, "catalog3.json")
BAD = ("one piece", "naruto", "fnaf", "stitch", "barbie", "dress", "skirt", "girl", "kawaii", "kitty", "bikini", "crop",
       "sonic", "spider", "goku", "pokemon", "mario", "minecraft", "bundle")
THEMES = [  # shirt/pants keyword, head keyword, back keyword (or None)
    ("armor", "titan helmet", None), ("police", "police hat", None), ("tracksuit", "headband", None),
    ("star", "star crown", "star wings"), ("space suit", "space helmet", "jetpack"), ("shadow", "shadow hood", None),
    ("sun", "sun crown", "wings"), ("moon", "moon", None), ("ocean", "octopus", None), ("lava", "lava", None),
    ("storm", "lightning", None), ("crystal", "crystal crown", None), ("spirit", "spirit", "wings"),
    ("jungle", "wolf", None), ("mage", "wizard", "cape"), ("knight", "knight helmet", "shield"),
    ("steampunk", "steampunk hat", None), ("void", "void", "void wings"), ("astral", "halo", "wings"),
    ("infinity", "infinity", None), ("red suit", "red crown", "red wings"), ("royal", "emperor crown", "royal cape"),
    ("white suit", "white crown", "white wings"), ("divine", "divine crown", "angel wings"), ("gold suit", "dominus", "golden wings"),
]


def search(kw, cat, sub, types, n):
    p = dict(Keyword=kw, Category=cat, Limit=30, SortType=1)
    if sub:
        p["Subcategory"] = sub
    time.sleep(0.6)
    try:
        with urllib.request.urlopen("https://catalog.roblox.com/v1/search/items/details?" + urllib.parse.urlencode(p), timeout=20) as r:
            data = json.load(r)["data"]
    except Exception as e:
        print("  ! search failed:", kw, e)
        return []
    out, seen = [], set()
    for x in sorted(data, key=lambda x: -(x.get("favoriteCount") or 0)):
        name = x["name"].lower().strip()
        if x.get("itemType") == "Asset" and x["assetType"] in types and name not in seen and not any(b in name for b in BAD):
            seen.add(name)
            out.append([x["id"], x["assetType"]])
    return out[:n]


cache = json.load(open(CACHE)) if os.path.exists(CACHE) else {}
for kw, head, back in THEMES:
    if kw in cache:
        continue
    t = dict(shirts=search(kw, 3, 56, {11}, 6), pants=search(kw, 3, 57, {12}, 6),
             heads=search(head, 11, None, {8, 41, 42}, 6), back=search(back, 11, None, {44, 45, 46, 47}, 3) if back else [])
    if not t["shirts"]:
        t["shirts"] = search(kw + " shirt", 3, 56, {11}, 6)
    if not t["pants"]:
        t["pants"] = search("black pants", 3, 57, {12}, 6)
    print(kw, {k: len(v) for k, v in t.items()})
    cache[kw] = t
    json.dump(cache, open(CACHE, "w"))

# rarities 1-25: parse the existing (verified) table
src = open(AV, encoding="utf-8").read()
rows = []
for block in re.findall(r"\t\{\n(.*?)\n\t\},?", src, re.S):
    row = []
    for sh, pa, acc in re.findall(r"shirt = (\d+), pants = (\d+), accessories = \{ (.*?) \} \}", block):
        row.append(dict(shirt=int(sh), pants=int(pa), acc=[[int(a), int(b)] for a, b in re.findall(r"\{ (\d+), (\d+) \}", acc)]))
    rows.append(row)
rows = rows[:25]
assert len(rows) == 25 and all(len(r) >= 4 for r in rows), [len(r) for r in rows]
HAIRS = [h["id"] for h in sum(json.load(open(os.path.join(S, "hair.json"))).values(), [])]
for r, row in enumerate(rows):
    if len(row) == 4:  # two more looks mixed from the four checked ones
        hair = lambda v: [a for a in v["acc"] if a[1] == 41]
        rest = lambda v: [a for a in v["acc"] if a[1] != 41]
        row.append(dict(shirt=row[2]["shirt"], pants=row[3]["pants"], acc=hair(row[1]) + rest(row[0])))
        row.append(dict(shirt=row[3]["shirt"], pants=row[0]["pants"], acc=hair(row[2]) + rest(row[1])))
for r, (kw, _, _) in enumerate(THEMES):
    t = cache[kw]
    assert t["shirts"] and t["pants"] and t["heads"], kw
    row = []
    for i in range(6):
        head = t["heads"][i % len(t["heads"])]
        acc = ([] if head[1] == 41 else [[HAIRS[(r * 3 + i) % len(HAIRS)], 41]]) + [head]
        if t["back"]:
            acc.append(t["back"][i % len(t["back"])])
        row.append(dict(shirt=t["shirts"][i % len(t["shirts"])][0], pants=t["pants"][i % len(t["pants"])][0], acc=acc))
    rows.append(row)

lines = ["-- AUTO-GENERATED by tools/catalog/outfits50.py from the Roblox catalog — real catalog items for every character.",
         "-- [rarity][title] = { shirt, pants, accessories = { {id, assetType}, ... } }", "return {"]
for row in rows:
    lines.append("\t{")
    for v in row:
        acc = ", ".join(f"{{ {a}, {b} }}" for a, b in v["acc"])
        lines.append(f"\t\t{{ shirt = {v['shirt']}, pants = {v['pants']}, accessories = {{ {acc} }} }},")
    lines.append("\t},")
lines.append("}")
open(AV, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("rarities:", len(rows), "looks:", sum(len(r) for r in rows))
